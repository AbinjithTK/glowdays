/**
 * Build the deployable artefact.
 *
 * Produces `dist-deploy/` containing one JavaScript file and the built web app,
 * ready to zip and upload.
 *
 * Bundling rather than shipping node_modules is not an optimisation, it is a
 * requirement. pnpm stores packages once and links them, so a naive zip of
 * node_modules captures symlinks that do not survive the archive and the
 * function fails at import time with a module-not-found for something that is
 * plainly there. Bundling sidesteps the whole class of problem.
 *
 * The web app is copied in alongside, so a single function serves the API and the
 * UI on one origin. That keeps CORS out of the request path and means one URL to
 * give a reviewer.
 */

import { cp, mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist-deploy');

async function exists(path) {
  try {
    await stat(path);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });

  const result = await build({
    entryPoints: [join(root, 'apps/api/src/lambda.ts')],
    outfile: join(out, 'index.mjs'),
    bundle: true,
    platform: 'node',
    target: 'node22',
    format: 'esm',
    sourcemap: true,
    minify: false,
    logLevel: 'info',
    metafile: true,
    /**
     * Excluded deliberately.
     *
     * pglite is the embedded WebAssembly Postgres used for local development. It
     * is reached through a dynamic import that only fires for a `pglite://` URL,
     * and env.ts refuses that scheme in production, so it can never load here.
     * Bundling it would add tens of megabytes of WASM to every cold start for
     * code that is unreachable.
     *
     * The AWS SDK is deliberately NOT external, even though the Node 22 Lambda
     * runtime ships SDK v3. The runtime includes the service clients, but
     * @aws-sdk/s3-request-presigner is a utility rather than a client and is not
     * guaranteed to be there. Presigning is how every photograph and mask is
     * read, so relying on it being present risks discovering it is missing after
     * deployment, on the feature the product cannot work without. Bundling costs
     * a couple of megabytes, pins the version, and makes the artefact runnable
     * locally - which is what allows the handler to be tested before it ships.
     */
    external: [
      '@electric-sql/pglite',
      // Also external, and this one is not obvious. The driver is reached
      // through a dynamic import, so marking only pglite external looks
      // sufficient - but drizzle-orm/pglite would then get bundled, and it
      // imports pglite statically. esbuild hoists that into a top-level import
      // of an external package, which Node resolves at load time and cannot
      // find. The result is a function that fails on its first cold start with
      // a module-not-found for a package deliberately excluded.
      'drizzle-orm/pglite',
    ],
    /**
     * esbuild leaves `import.meta` alone in ESM output, which is what we want:
     * server.ts uses it to decide whether it was run directly, and under Lambda
     * it is imported rather than executed, so that branch correctly stays off.
     */
    banner: {
      /**
       * Give the bundle a real `require`.
       *
       * The AWS SDK ships CommonJS, and its modules call `require('buffer')` and
       * friends. In ESM output esbuild replaces `require` with a stub that
       * throws "Dynamic require of X is not supported", so the bundle loads and
       * then dies the moment the SDK touches a Node builtin.
       *
       * esbuild's own shim defers to an outer `require` when one exists, so
       * defining it from createRequire is enough to make the CJS dependencies
       * behave. This is the documented workaround for CJS-in-ESM bundles.
       */
      js: [
        '// Glowdays API bundle. Generated by scripts/bundle-api.mjs - do not edit.',
        "import { createRequire as __glowdaysRequire } from 'node:module';",
        'const require = __glowdaysRequire(import.meta.url);',
      ].join('\n'),
    },
  });

  // Copy the built web app in. The API serves it when WEB_DIST_DIR points here.
  const webDist = join(root, 'apps/web/dist');
  if (await exists(join(webDist, 'index.html'))) {
    await cp(webDist, join(out, 'web'), { recursive: true });
    console.log('bundled the web app from apps/web/dist');
  } else {
    console.warn(
      'apps/web/dist is missing, so this artefact serves the API only. ' +
        'Run `pnpm --filter @glowdays/web build` first.',
    );
  }

  // Migrations are read from disk at runtime by the migration runner, so they
  // travel with the artefact rather than being baked into the bundle.
  await cp(join(root, 'apps/api/migrations'), join(out, 'migrations'), { recursive: true });

  const sizes = Object.entries(result.metafile.outputs)
    .map(([file, meta]) => `${file.replace(/\\/g, '/')}  ${(meta.bytes / 1024).toFixed(0)} kB`)
    .join('\n  ');
  console.log(`\noutputs:\n  ${sizes}`);

  await writeFile(
    join(out, 'BUILD.txt'),
    [
      `built ${new Date().toISOString()}`,
      'entry: index.mjs, handler: index.handler',
      'external: @electric-sql/pglite, @aws-sdk/*',
    ].join('\n'),
    'utf8',
  );

  console.log('\nartefact ready at dist-deploy/');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
